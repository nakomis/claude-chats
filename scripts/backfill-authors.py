#!/usr/bin/env python3
"""Set author, tool_name and model on rows captured before the hook knew them (HOME-311).

Rows captured before HOME-310 reached Postgres with ``author = 'unknown'``:
about 80,000 of them, half of everything up to 25 Aug 2026. Anything that
filters on author (the conversation map's per-author fits, search) has had to
guess for those, and the guess is poor: a regex on the text calls most
command output human.

Where the transcript still exists, nothing needs guessing. This reads every
transcript with the hook's own ``build_records`` (one implementation of what a
captured message is, not two) and prints SQL that sets the three columns from
it. Assistant rows need no transcript at all: ``classify_author`` calls every
one of them 'claude', so those are set from ``role`` alone, with model left
NULL because only the transcript knows it.

Rows with neither stay 'unknown'. Claude Code deletes old transcripts, so on
21 Oct 2026 phi's own held only 5,236 of the unknown rows; the rest of
June to August are recoverable only from Time Machine. Restore old
``~/.claude/projects`` folders somewhere and pass each with ``--projects``:
a message found in any of them counts. What no transcript covers is not
guessed at, because the classifier measured on later rows does not transfer
to April and May (see HOME-311).

It prints rather than connects: the Macs have no route to Luke's Postgres, and
it has to run on every Mac that holds transcripts. Review the output, then:

    python3 scripts/backfill-authors.py [--projects DIR ...] > /tmp/authors.sql
    ssh luke 'docker exec -i claude-chats-db psql -U claude -d claude_chats \\
        -v ON_ERROR_STOP=1' < /tmp/authors.sql

Safe to run more than once, from each Mac in any order: only rows still
'unknown' are touched, so nothing the hook wrote is ever overwritten, and a
second run finds nothing left to do. Messages not in the database match
nothing.
"""

import argparse
import glob
import json
import os
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(REPO, "hook"))

from hook.record import build_records  # noqa: E402


def _entries(path: str) -> list[dict]:
    out = []
    with open(path, errors="replace") as fh:
        for line in fh:
            if line.strip():
                try:
                    out.append(json.loads(line))
                except json.JSONDecodeError:
                    pass  # a half-written last line on a live session
    return out


def _copy_field(value: str | None) -> str:
    """One field of COPY's text format: \\N for NULL, the specials escaped."""
    if value is None:
        return r"\N"
    return (value.replace("\\", "\\\\").replace("\t", "\\t")
            .replace("\n", "\\n").replace("\r", "\\r"))


def authors(projects: list[str]) -> dict[str, tuple[str, str | None, str | None]]:
    """message_uuid -> (author, tool_name, model) for every transcript message.

    Recursive, so subagent transcripts are read too. A message appearing in
    more than one file (a resumed or forked session copies its history, and
    successive backups hold the same transcript) classifies the same way in
    each, so the last one read simply wins.
    """
    paths = []
    for d in projects:
        paths += glob.glob(os.path.join(d, "**", "*.jsonl"), recursive=True)
    out = {}
    for path in sorted(paths):
        session_id = os.path.basename(path)[: -len(".jsonl")]
        records, _ = build_records(_entries(path), session_id, "", "", None, None)
        for r in records:
            out[r["message_uuid"]] = (r["author"], r["tool_name"], r["model"])
    return out


SQL_HEAD = """\
-- Generated by scripts/backfill-authors.py (HOME-311).
BEGIN;
SET LOCAL lock_timeout = '10s';
CREATE TEMP TABLE author_backfill (
    message_uuid TEXT PRIMARY KEY,
    author       TEXT NOT NULL,
    tool_name    TEXT,
    model        TEXT
) ON COMMIT DROP;
COPY author_backfill (message_uuid, author, tool_name, model) FROM STDIN;
"""

# Two statements, each reporting what it changed by author. The transcript
# pass runs first so that assistant rows it can see get their model; the
# role pass then covers assistant rows whose transcript is gone.
SQL_TAIL = """\
\\.
WITH changed AS (
    UPDATE messages m
       SET author = b.author, tool_name = b.tool_name, model = b.model
      FROM author_backfill b
     WHERE m.message_uuid = b.message_uuid AND m.author = 'unknown'
    RETURNING m.author
)
SELECT 'from transcripts' AS source, author, count(*) FROM changed GROUP BY author ORDER BY author;
WITH changed AS (
    UPDATE messages SET author = 'claude'
     WHERE author = 'unknown' AND role = 'assistant'
    RETURNING author
)
SELECT 'assistant role' AS source, author, count(*) FROM changed GROUP BY author;
SELECT 'still unknown' AS source, role, count(*) FROM messages
 WHERE author = 'unknown' GROUP BY role ORDER BY role;
COMMIT;
"""


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument(
        "--projects", action="append", metavar="DIR",
        help="a Claude Code projects directory; repeat for restored backups "
             "(default: ~/.claude/projects)",
    )
    args = ap.parse_args()

    found = authors(args.projects or [os.path.expanduser("~/.claude/projects")])
    sys.stdout.write(SQL_HEAD)
    for uuid, (author, tool_name, model) in sorted(found.items()):
        sys.stdout.write("\t".join(_copy_field(v) for v in (uuid, author, tool_name, model)) + "\n")
    sys.stdout.write(SQL_TAIL)

    counts = {}
    for author, _, _ in found.values():
        counts[author] = counts.get(author, 0) + 1
    print("-- " + ", ".join(f"{n:,} {a}" for a, n in sorted(counts.items()))
          + " message(s) in transcripts", file=sys.stderr)


if __name__ == "__main__":
    main()
