#!/bin/sh
# Write firmware/full/main/wifi_secrets.h (gitignored) from the shared Wi-Fi
# credentials in SSM (/Nakomis/Wifi/SSID, /Nakomis/Wifi/Password), the same
# place nakostat's generate_secrets.py reads. Needs a live `aws sso login`.
set -eu
out="$(dirname "$0")/../firmware/full/main/wifi_secrets.h"
ssid=$(aws ssm get-parameter --name /Nakomis/Wifi/SSID --with-decryption --query Parameter.Value --output text)
pass=$(aws ssm get-parameter --name /Nakomis/Wifi/Password --with-decryption --query Parameter.Value --output text)
umask 077
python3 - "$out" "$ssid" "$pass" <<'EOF'
import json, sys
out, ssid, pw = sys.argv[1:]
open(out, 'w').write('// generated by host/gen_wifi_secrets.sh; do not commit\n'
                     f'#define WIFI_SSID {json.dumps(ssid)}\n#define WIFI_PASS {json.dumps(pw)}\n')
EOF
echo "wrote $out"
