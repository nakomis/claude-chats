"""Write firmware/full/main/longtest.h: long test texts with their reference vectors.

mxtest.bin's texts stop at 140 tokens. CHATS-4 lets one pass carry a whole
message (up to 512 tokens), so the firmware also embeds two long texts (public:
slices of this README, frozen in long_texts.json) and checks them against Ollama and against the emulation of the
lean layout (lean.py). Generated, like mxcrc.h; needs Ollama running.

    python gen_long.py [../firmware/full/main/longtest.h]
"""
import json
import sys
import urllib.request
from pathlib import Path

import numpy as np

import lean
import mxbai as M

# Frozen (long_texts.json): two slices of this README as it was on 12 Oct 2026, 391 tokens and
# well past 512 (truncated). Frozen because the firmware's self-test pins their output vectors.
TEXTS = json.loads((Path(__file__).resolve().parent / 'long_texts.json').read_text())


def ollama(t):
    req = urllib.request.Request('http://localhost:11434/api/embed',
                                 json.dumps({'model': 'mxbai-embed-large', 'input': t}).encode())
    return np.array(json.load(urllib.request.urlopen(req))['embeddings'][0], np.float32)


def c_str(s):
    out = []
    for b in s.encode():
        c = chr(b)
        out.append('\\\\' if c == '\\' else '\\"' if c == '"' else '\\n' if c == '\n' else c if 32 <= b < 127 else f'\\{b:03o}')
    return '"' + ''.join(out) + '"'


def main():
    dst = sys.argv[1] if len(sys.argv) > 1 else '../firmware/full/main/longtest.h'
    rows = []
    for t in TEXTS:
        ids, total = M.TOK.encode(t, total=True)
        ref, emu = ollama(t), lean.embed_lean(ids).astype(np.float32)
        print(f'{len(t)} chars, {total} tokens -> {len(ids)}: lean emulation vs Ollama cos {M.cos(emu, ref):.6f}')
        rows.append((t, len(ids), ref, emu))
    with open(dst, 'w') as f:
        f.write('// Generated by host/gen_long.py: long texts, token counts, Ollama and lean-emulation vectors.\n')
        f.write(f'#define N_LONG {len(rows)}\n')
        f.write('static const struct { const char *text; int n_tok; float ref[1024], emu[1024]; } LONG[N_LONG] = {\n')
        for t, n, ref, emu in rows:
            f.write('  { ' + c_str(t) + f',\n    {n},\n')
            for v in (ref, emu):
                f.write('    { ' + ', '.join(f'{x:.9g}f' for x in v) + ' },\n')
            f.write('  },\n')
        f.write('};\n')
    print('wrote', dst)


if __name__ == '__main__':
    main()
