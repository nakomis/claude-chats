"""Generate firmware/full/main/mxcrc.h: the CRC32 of every section of mxbai.bin.

The firmware checks each section it streams off the card against these. Run after
prep_full.py, on the same mxbai.bin you copy to the card:

    python gen_crc.py mxbai.bin ../firmware/full/main/mxcrc.h
"""
import struct
import sys
import zlib

src = sys.argv[1] if len(sys.argv) > 1 else 'mxbai.bin'
dst = sys.argv[2] if len(sys.argv) > 2 else '../firmware/full/main/mxcrc.h'
f = open(src, 'rb')
h = f.read(1024)
magic, ver, L, K, V, D, FF, P = struct.unpack_from('<4sIIIIIII', h)
assert magic == b'MXB1', magic
G = 7
goff = struct.unpack_from(f'<{G}I', h, 32)
loff = struct.unpack_from(f'<{L}I', h, 32 + 4 * G)
mats = [(D, D)] * 4 + [(D, FF), (FF, D)]        # (in, out): attn_q, attn_k, attn_v, attn_output, ffn_up, ffn_down
sizes = []
for i, o in mats:
    sizes += [i * o, o * 4, o * 4, K * 2, o * K * 4]   # wq, ws, bias, oidx, wo
sizes += [D * 4] * 4                                   # attn_output_norm w/b, layer_output_norm w/b
glen = [V * D, V * 4, P * D * 4, D * 4, D * 4, D * 4]  # tok_q, tok_s, pos, type0, embd_norm w/b
crc = []
for li in range(L):
    f.seek(loff[li])
    tab = struct.unpack('<34I', f.read(34 * 4))
    row = []
    for s in range(34):
        f.seek(loff[li] + tab[s])
        row.append(zlib.crc32(f.read(sizes[s])))
    crc.append(row)
gc = []
for g in range(6):
    f.seek(goff[g])
    gc.append(zlib.crc32(f.read(glen[g])))
f.seek(goff[6])                                        # vocab: V NUL-terminated strings
vocab = f.read(loff[0] - goff[6])
vlen = [i for i, b in enumerate(vocab) if b == 0][V - 1] + 1
gc.append(zlib.crc32(vocab[:vlen]))
with open(dst, 'w') as o:
    o.write('// CRC32 (zlib) of each section of mxbai.bin; generated by host/gen_crc.py.\n')
    o.write(f'#define VOCAB_LEN {vlen}\n')
    o.write('static const uint32_t glob_crc[7] = { ' + ', '.join(f'0x{c:08x}' for c in gc) + ' };\n')
    o.write(f'static const uint32_t layer_crc[{L}][34] = {{\n')
    for r in crc:
        o.write('    { ' + ', '.join(f'0x{c:08x}' for c in r) + ' },\n')
    o.write('};\n')
print(f'{dst}: {L} layers x 34 sections + {len(gc)} globals')
