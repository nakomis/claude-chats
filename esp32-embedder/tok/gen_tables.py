"""Generate tok_tables.h from llama.cpp's own Unicode data.

The tokeniser has to match the llama.cpp that Ollama ships (llama-server,
pinned in Ollama's LLAMA_CPP_VERSION), not Python's unicodedata or HF, so the
tables come from that tag's src/unicode-data.cpp:

    python gen_tables.py [unicode-data.cpp]     # default: download tag below

Three tables, all looked up after llama.cpp's single-codepoint NFD map:
  - class runs: what `llm_tokenizer_wpm_session::preprocess` does with each
    codepoint (whitespace / drop / split off as a one-character word / keep)
  - lowercase pairs (unicode_map_lowercase)
  - NFD ranges (unicode_ranges_nfd: first, last, replacement)
"""
import re
import sys
import urllib.request
from pathlib import Path

TAG = 'b11351'
URL = f'https://raw.githubusercontent.com/ggml-org/llama.cpp/{TAG}/src/unicode-data.cpp'
MAX_CP = 0x110000

# unicode_cpt_flags bits (src/unicode.h)
F_ACCENT, F_PUNCT, F_SYMBOL, F_CONTROL = 0x10, 0x20, 0x40, 0x80
# classes, as tok.c reads them
KEEP, WS, DROP, SPLIT = 0, 1, 2, 3


def table(src, name):
    body = re.search(name + r'\s*=\s*\{(.*?)\n\};', src, re.S).group(1)
    return body


def is_chinese(cp):
    # llm_tokenizer_wpm_session::is_chinese_char, including its 0x2B920 quirk
    return any(a <= cp <= b for a, b in (
        (0x04E00, 0x09FFF), (0x03400, 0x04DBF), (0x20000, 0x2A6DF), (0x2A700, 0x2B73F),
        (0x2B740, 0x2B81F), (0x2B920, 0x2CEAF), (0x0F900, 0x0FAFF), (0x2F800, 0x2FA1F)))


def main():
    src = Path(sys.argv[1]).read_text() if len(sys.argv) > 1 else urllib.request.urlopen(URL).read().decode()

    runs = [(int(a, 16), int(b, 16)) for a, b in re.findall(r'\{(0x[0-9A-F]+), (0x[0-9A-F]+)\}', table(src, 'unicode_ranges_flags'))]
    ws = {int(x, 16) for x in re.findall(r'0x[0-9A-F]+', table(src, 'unicode_set_whitespace'))}
    lower = [(int(a, 16), int(b, 16)) for a, b in re.findall(r'\{(0x[0-9A-F]+), (0x[0-9A-F]+)\}', table(src, 'unicode_map_lowercase'))]
    nfd = [tuple(int(x, 16) for x in t) for t in re.findall(r'\{(0x[0-9A-F]+), (0x[0-9A-F]+), (0x[0-9A-F]+)\}', table(src, 'unicode_ranges_nfd'))]
    assert runs[0][0] == 0 and runs[-1][0] == MAX_CP

    flags = [0] * MAX_CP
    for (a, f), (b, _) in zip(runs, runs[1:]):
        flags[a:b] = [f] * (b - a)

    def cls(cp):
        f = flags[cp]
        if cp in ws:
            return WS
        if cp == 0 or cp == 0xFFFD or f & (F_CONTROL | F_ACCENT):
            return DROP
        if f & F_PUNCT or (cp < 0x7F and f & F_SYMBOL) or is_chinese(cp):
            return SPLIT
        return KEEP

    cruns, prev = [], None
    for cp in range(MAX_CP):
        c = cls(cp)
        if c != prev:
            cruns.append((cp, c))
            prev = c

    def rows(items, per, fmt):
        out = []
        for i in range(0, len(items), per):
            out.append('    ' + ' '.join(fmt(x) for x in items[i:i + per]))
        return '\n'.join(out)

    h = f"""// Generated by gen_tables.py from llama.cpp {TAG} src/unicode-data.cpp (MIT). Do not edit.
#pragma once
#include <stdint.h>

// codepoint class runs: (first codepoint << 2) | class; a run lasts until the next one starts
#define TOK_KEEP  {KEEP}
#define TOK_WS    {WS}
#define TOK_DROP  {DROP}
#define TOK_SPLIT {SPLIT}
#define TOK_N_CLASS {len(cruns)}
static const uint32_t tok_class[TOK_N_CLASS] = {{
{rows(cruns, 6, lambda r: f'0x{(r[0] << 2) | r[1]:07X},')}
}};

// lowercase map, sorted by codepoint: from, to
#define TOK_N_LOWER {len(lower)}
static const uint32_t tok_lower[TOK_N_LOWER][2] = {{
{rows(lower, 4, lambda r: f'{{0x{r[0]:05X}, 0x{r[1]:05X}}},')}
}};

// NFD ranges, sorted: first, last, replacement
#define TOK_N_NFD {len(nfd)}
static const uint32_t tok_nfd[TOK_N_NFD][3] = {{
{rows(nfd, 3, lambda r: f'{{0x{r[0]:05X}, 0x{r[1]:05X}, 0x{r[2]:05X}}},')}
}};
"""
    out = Path(__file__).with_name('tok_tables.h')
    out.write_text(h)
    print(f'{out.name}: {len(cruns)} class runs, {len(lower)} lowercase, {len(nfd)} NFD; '
          f'~{(len(cruns) * 4 + len(lower) * 8 + len(nfd) * 12) / 1024:.0f} KB')


if __name__ == '__main__':
    main()
